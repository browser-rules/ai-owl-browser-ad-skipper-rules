function normalizeLocale(value) {
  if (!value) return "en";
  const tag = value.replace("_", "-");
  const lowerTag = tag.toLowerCase();
  if (lowerTag === "id" || lowerTag === "in" || lowerTag.startsWith("id-") || lowerTag.startsWith("in-")) {
    return "id-ID";
  }
  const language = lowerTag.split("-")[0];
  return localeOptions.some((option) => option.code === language) ? language : "en";
}

function getSelectedLocale() {
  const savedLocale = window.localStorage.getItem(storageKey);
  if (savedLocale) return normalizeLocale(savedLocale);
  for (const language of navigator.languages || [navigator.language]) {
    const locale = normalizeLocale(language);
    if (locale !== "en") return locale;
  }
  return "en";
}

function translate(locale, key) {
  return messages[locale]?.[key] || messages.en[key] || "";
}

function applyLocale(locale) {
  const normalizedLocale = normalizeLocale(locale);
  document.documentElement.lang = normalizedLocale;
  document.documentElement.dir = rtlLocales.has(normalizedLocale) ? "rtl" : "ltr";
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const value = translate(normalizedLocale, node.dataset.i18n);
    if (value) node.textContent = value;
  });
  document.querySelectorAll("#languageSelect").forEach((select) => {
    select.value = normalizedLocale;
  });
}

function setupLanguageSelector() {
  const selectedLocale = getSelectedLocale();
  document.querySelectorAll("#languageSelect").forEach((select) => {
    localeOptions.forEach((option) => {
      const item = document.createElement("option");
      item.value = option.code;
      item.textContent = option.label;
      select.appendChild(item);
    });
    select.value = selectedLocale;
    select.addEventListener("change", () => {
      window.localStorage.setItem(storageKey, select.value);
      applyLocale(select.value);
    });
  });
  applyLocale(selectedLocale);
}

function setupRuleLinks() {
  document.querySelectorAll("[data-rule-url]").forEach((node) => {
    node.textContent = ruleUrl;
  });
  document.querySelectorAll("[data-rule-href]").forEach((node) => {
    node.href = ruleUrl;
  });
}

function bindCopyRuleUrl(button, label) {
  if (!button) return;
  button.addEventListener("click", async () => {
    await navigator.clipboard.writeText(ruleUrl);
    const locale = normalizeLocale(window.localStorage.getItem(storageKey) || document.documentElement.lang);
    const labelNode = label || button;
    const originalText = labelNode.textContent;
    labelNode.textContent = translate(locale, "action.copied");
    window.setTimeout(() => {
      labelNode.textContent = originalText;
    }, 1600);
  });
}

